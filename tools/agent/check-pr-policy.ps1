param(
    [Parameter(Mandatory = $true)]
    [int] $PullRequest
)

$prJson = gh pr view $PullRequest --json title,body,labels,baseRefName,headRefName,url
if ($LASTEXITCODE -ne 0) {
    Write-Error "Unable to read pull request $PullRequest."
    exit 1
}

$pr = $prJson | ConvertFrom-Json
$labels = @($pr.labels | ForEach-Object { $_.name })
$head = [string] $pr.headRefName
$base = [string] $pr.baseRefName
$failures = @()

$titlePattern = '^(feat|fix|refactor|test|docs|chore|perf|build|ci)(\([a-z0-9-]+\))?: .{1,72}$'
if ($pr.title -notmatch $titlePattern) {
    $failures += "PR title must use Conventional Commits in English."
}

if ($pr.body -notmatch '#\d+') {
    $failures += "PR body must link a related issue."
}

if ($labels -contains 'do-not-merge') {
    $failures += "The do-not-merge label is present."
}

if ($labels -contains 'agent:changes-requested') {
    $failures += "The agent:changes-requested label is present."
}

if ($base -eq 'develop') {
    if ($head -notmatch '^(feature|bugfix|chore|docs|test|refactor|backmerge)/') {
        $failures += "Pull requests to develop must come from feature, bugfix, chore, docs, test, refactor, or backmerge branches."
    }
}
elseif ($base -eq 'main') {
    if ($head -notmatch '^(release|hotfix)/') {
        $failures += "Pull requests to main must come from release or hotfix branches."
    }
}
else {
    $failures += "Unsupported target branch: $base."
}

$combined = "$($pr.title)`n$($pr.body)"
$forbidden = @(
    'generated with',
    'generated by ai',
    'ai-generated',
    'llm-generated',
    'co-authored-by: opencode',
    'co-authored-by: claude',
    'co-authored-by: chatgpt',
    'co-authored-by: copilot',
    'chatgpt',
    'copilot',
    'ai assistant',
    'openai',
    'anthropic'
)

foreach ($phrase in $forbidden) {
    if ($combined -match [regex]::Escape($phrase)) {
        $failures += "Forbidden attribution phrase found: $phrase."
    }
}

if ($failures.Count -gt 0) {
    $failures | ForEach-Object { Write-Error $_ }
    exit 1
}

Write-Output "Pull request policy passed for $($pr.url)."
